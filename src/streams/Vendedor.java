package streams;

public class Vendedor {

    final String nome;
    final Integer vendasMes;
    final boolean isComportamento;

    public Vendedor(String nome, Integer vendasMes, boolean isComportamento) {
        this.nome = nome;
        this.vendasMes = vendasMes;
        this.isComportamento = isComportamento;
    }

}
